#!/usr/bin/env python
"""Aggregate every finished run into CSV tables, LaTeX tables and a claims report."""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from afa_ssl.eval.aggregate import (METHOD_LABELS, SUP_CRITERIA, best_supervised, latex_table,  # noqa: E402
                                    load_runs, mean_std_table, paired_vs)

OUT = Path("experiments/aggregate")
TAB = Path("paper/tables")


def sig(p: float) -> str:
    return "yes" if (np.isfinite(p) and p < 0.05) else "no"


def claims_report(df: pd.DataFrame) -> str:
    lines = ["# Claims report (auto-generated by scripts/aggregate.py)", ""]
    main = df[df.experiment == "main"]
    if main.empty:
        return "\n".join(lines + ["no main-grid runs found"])
    best = best_supervised(main)
    # C1
    lines += ["## C1: label-scarce advantage (n_labels in {50,100}) on metabric and metabric_semisynth", "",
              "| dataset | n_labels | best sup. | ours | best sup. AUCC | diff | p (t) | d_z | wins | holds |",
              "|---|---|---|---|---|---|---|---|---|---|"]
    for ds in ["metabric", "metabric_semisynth"]:
        for n in sorted(main[main.dataset == ds].n_labels.unique()):
            if n > 100:
                continue
            b = best.get((ds, n))
            if b is None:
                continue
            pv = paired_vs(main[(main.dataset == ds) & (main.n_labels == n)], "ours", [b, "rand"])
            r = pv[pv.other == b].iloc[0]
            rr = pv[pv.other == "rand"].iloc[0]
            holds = "yes" if (r.mean_diff > 0 and r.p_t < 0.05 and rr.mean_diff > 0) else "no"
            lines.append(f"| {ds} | {n} | {METHOD_LABELS[b]} | {r.mean_a:.3f} | {r.mean_b:.3f} | "
                         f"{r.mean_diff:+.3f} | {r.p_t:.3g} | {r.d_z:.2f} | {r.wins}/{r.n} | {holds} |")
    # C2
    lines += ["", "## C2: ours vs the same predictive model with a random acquisition order", "",
              "| dataset | n_labels | ours | ens_rand | diff | p (t) | d_z | wins |", "|---|---|---|---|---|---|---|---|"]
    pv = paired_vs(main, "ours", ["ens_rand"])
    for _, r in pv.sort_values(["dataset", "n_labels"]).iterrows():
        lines.append(f"| {r.dataset} | {r.n_labels} | {r.mean_a:.3f} | {r.mean_b:.3f} | {r.mean_diff:+.3f} | "
                     f"{r.p_t:.3g} | {r.d_z:.2f} | {r.wins}/{r.n} |")
    # C3
    lines += ["", "## C3: label-efficiency gap (ours - best supervised) on metabric by n_labels", ""]
    sub = main[main.dataset == "metabric"]
    for n in sorted(sub.n_labels.unique()):
        b = best.get(("metabric", n))
        pv = paired_vs(sub[sub.n_labels == n], "ours", [b])
        if not pv.empty:
            r = pv.iloc[0]
            lines.append(f"- n_labels={n}: gap {r.mean_diff:+.3f} (vs {METHOD_LABELS[b]}, p={r.p_t:.3g}, wins {r.wins}/{r.n})")
    # C4
    lines += ["", "## C4: ground-truth recovery at 50 labels (precision@k, redundancy@k)", "",
              "| dataset | method | precision@k | group coverage@k | redundancy@k |", "|---|---|---|---|---|"]
    for ds in ["synth_scm", "metabric_semisynth"]:
        s = main[(main.dataset == ds) & (main.n_labels == 50)]
        if s.empty or "precision_at_k" not in s:
            continue
        g = s.groupby("method")[["precision_at_k", "group_coverage_at_k", "redundancy_at_k"]].agg(["mean", "std"])
        for m in ["rand", "unc", "eig_sup", "eig_sup_ens", "ours_sslonly", "ours"]:
            if m in g.index:
                lines.append(f"| {ds} | {METHOD_LABELS[m]} | {g.loc[m, ('precision_at_k','mean')]:.3f} ± {g.loc[m, ('precision_at_k','std')]:.3f} | "
                             f"{g.loc[m, ('group_coverage_at_k','mean')]:.3f} | {g.loc[m, ('redundancy_at_k','mean')]:.3f} ± {g.loc[m, ('redundancy_at_k','std')]:.3f} |")
        for other in ["rand", "unc", "eig_sup", "eig_sup_ens"]:
            pv = paired_vs(s, "ours", [other], metric="precision_at_k")
            if not pv.empty:
                r = pv.iloc[0]
                lines.append(f"- {ds}: precision@k ours vs {other}: {r.mean_diff:+.3f}, p={r.p_t:.3g}, wins {r.wins}/{r.n}")
        pv = paired_vs(s, "ours", ["eig_sup"], metric="redundancy_at_k")
        if not pv.empty:
            r = pv.iloc[0]
            lines.append(f"- {ds}: redundancy@k ours - eig_sup: {r.mean_diff:+.3f} (negative is good), p={r.p_t:.3g}")
    # C5 (ablation experiment)
    abl = df[df.experiment == "ablation"]
    if not abl.empty:
        lines += ["", "## C5: component ablation (metabric, 50 labels unless noted)", "",
                  "| dataset | n_labels | variant | AUCC | ours | diff (ours - variant) | p (t) | wins |", "|---|---|---|---|---|---|---|---|"]
        for (ds, n), s in abl.groupby(["dataset", "n_labels"]):
            others = [m for m in s.method.unique() if m != "ours"]
            pv = paired_vs(s, "ours", others)
            for _, r in pv.iterrows():
                lines.append(f"| {ds} | {n} | {METHOD_LABELS.get(r.other, r.other)} | {r.mean_b:.3f} | {r.mean_a:.3f} | "
                             f"{r.mean_diff:+.3f} | {r.p_t:.3g} | {r.wins}/{r.n} |")
    cost = df[df.experiment == "cost"]
    if not cost.empty:
        lines += ["", "## C5 (cost): heterogeneous costs, cost-aware vs cost-blind (AUCC over cost)", "",
                  "| dataset | n_labels | pair | aware | blind | diff | p (t) | wins |", "|---|---|---|---|---|---|---|---|"]
        for (ds, n), s in cost.groupby(["dataset", "n_labels"]):
            for a, b in [("ours", "ours_costblind"), ("eig_sup", "eig_sup_costblind"), ("ours", "eig_sup")]:
                pv = paired_vs(s, a, [b])
                if not pv.empty:
                    r = pv.iloc[0]
                    lines.append(f"| {ds} | {n} | {a} vs {b} | {r.mean_a:.3f} | {r.mean_b:.3f} | {r.mean_diff:+.3f} | {r.p_t:.3g} | {r.wins}/{r.n} |")
    # C6 (robustness / transfer experiments)
    for exp, title in [("missing", "C6a: 30% MCAR missingness in the pool"), ("noise", "C6b: test-time noise"),
                       ("transfer", "C6c: cross-cohort transfer")]:
        s = df[df.experiment == exp]
        if s.empty:
            continue
        lines += ["", f"## {title}", "", "| dataset | n_labels | method | AUCC mean ± std |", "|---|---|---|---|"]
        g = s.groupby(["dataset", "n_labels", "method"])["aucc"].agg(["mean", "std"]).reset_index()
        for _, r in g.iterrows():
            lines.append(f"| {r.dataset} | {r.n_labels} | {METHOD_LABELS.get(r.method, r.method)} | {r['mean']:.3f} ± {r['std']:.3f} |")
        pv = paired_vs(s, "ours", ["rand", "eig_sup", "eig_sup_ens", "ens_rand"])
        for _, r in pv.iterrows():
            lines.append(f"- {r.dataset} n={r.n_labels}: ours vs {r.other}: {r.mean_diff:+.3f}, p={r.p_t:.3g}, wins {r.wins}/{r.n}")
    return "\n".join(lines)


def main() -> None:
    df = load_runs()
    if df.empty:
        print("no runs found")
        return
    OUT.mkdir(parents=True, exist_ok=True)
    TAB.mkdir(parents=True, exist_ok=True)
    df.drop(columns=["acc_curve"]).to_csv(OUT / "all_runs.csv", index=False)
    df.to_pickle(OUT / "all_runs.pkl")
    ms = mean_std_table(df[df.experiment == "main"])
    ms.to_csv(OUT / "main_mean_std.csv", index=False)
    main = df[df.experiment == "main"]
    if not main.empty:
        paired_vs(main, "ours", [m for m in METHOD_LABELS if m != "ours"]).to_csv(OUT / "main_paired_vs_ours.csv", index=False)
        core = ["rand", "static_sup", "unc", "eig_sup", "er_sup", "ecd_sup", "eig_sup_ens", "ssl_rand", "ens_rand", "ours_sslonly", "ours"]
        for ds in main.dataset.unique():
            (TAB / f"aucc_{ds}.tex").write_text(latex_table(main, ds, core))
    for exp in ("ablation", "cost", "missing", "noise", "transfer", "capacity", "poolfrac", "objective", "scale"):
        s = df[df.experiment == exp]
        if not s.empty:
            mean_std_table(s).to_csv(OUT / f"{exp}_mean_std.csv", index=False)
            for ds in s.dataset.unique():
                (TAB / f"aucc_{exp}_{ds}.tex").write_text(latex_table(s, ds, sorted(s.method.unique())))
    rep = claims_report(df)
    (OUT / "claims_report.md").write_text(rep)
    print(rep)
    print(f"\nwrote {OUT}/ and {TAB}/ ({len(df)} method-rows from {df.run_id.nunique()} runs)")


if __name__ == "__main__":
    main()
